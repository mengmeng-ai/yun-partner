import { contextBridge, ipcRenderer } from 'electron';

// Minimal, explicit IPC surface. Renderer never gets Node or Electron directly.
contextBridge.exposeInMainWorld('api', {
  lockStatus: () => ipcRenderer.invoke('lock:status'),
  lockSet: (pw: string) => ipcRenderer.invoke('lock:set', pw),
  lockUnlock: (pw: string) => ipcRenderer.invoke('lock:unlock', pw),
  lockLock: () => ipcRenderer.invoke('lock:lock'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (s: unknown) => ipcRenderer.invoke('settings:save', s),
  pickWorkspace: () => ipcRenderer.invoke('settings:pick-workspace'),
  getSoul: () => ipcRenderer.invoke('soul:get'),
  saveSoul: (t: string) => ipcRenderer.invoke('soul:save', t),
  getProfile: () => ipcRenderer.invoke('profile:get'),
  saveProfile: (p: unknown) => ipcRenderer.invoke('profile:save', p),
  listMemory: () => ipcRenderer.invoke('memory:list'),
  addMemory: (text: string, tags: string[]) => ipcRenderer.invoke('memory:add', text, tags),
  deleteMemory: (id: string) => ipcRenderer.invoke('memory:delete', id),
  recallMemory: (q: string) => ipcRenderer.invoke('memory:recall', q),
  listWiki: () => ipcRenderer.invoke('wiki:list'),
  saveWiki: (title: string, body: string) => ipcRenderer.invoke('wiki:save', title, body),
  getHistory: () => ipcRenderer.invoke('history:get'),
  clearHistory: () => ipcRenderer.invoke('history:clear'),
  listModels: () => ipcRenderer.invoke('models:list'),
  listFiles: (rel: string) => ipcRenderer.invoke('files:list', rel),
  readFile: (rel: string) => ipcRenderer.invoke('files:read', rel),
  sendChat: (text: string) => ipcRenderer.invoke('chat:send', text),
  stopChat: () => ipcRenderer.invoke('chat:stop'),
  // Full-duplex STT: transcribe one recorded segment via Whisper (main process).
  transcribeVoice: (audioB64: string, mimeType: string) => ipcRenderer.invoke('voice:transcribe', { audioB64, mimeType }),
  respondApproval: (id: string, ok: boolean) => ipcRenderer.send('approval:respond', id, ok),
  onChatDelta: (cb: (t: string) => void) => ipcRenderer.on('chat:delta', (_e, t: string) => cb(t)),
  onChatDone: (cb: (m: unknown) => void) => ipcRenderer.on('chat:done', (_e, m: unknown) => cb(m)),
  onApproval: (cb: (r: { id: string; summary: string }) => void) =>
    ipcRenderer.on('approval:request', (_e, r: { id: string; summary: string }) => cb(r)),
  // Phase 1 extra tools + monitor / undo / wiki / semantic
  listTools2: () => ipcRenderer.invoke('tools2:list'),
  callTool2: (name: string, args: Record<string, unknown>) => ipcRenderer.invoke('tools2:call', name, args),
  getSystemStatus: () => ipcRenderer.invoke('system:status'),
  listUndo: () => ipcRenderer.invoke('undo:list'),
  restoreUndo: (id: string) => ipcRenderer.invoke('undo:restore', id),
  wikiGraph: () => ipcRenderer.invoke('wiki:graph'),
  semanticRecall: (q: string) => ipcRenderer.invoke('memory:semantic', q),
  writeFile: (rel: string, content: string) => ipcRenderer.invoke('files:write', rel, content),
  // Employee team
  teamList: () => ipcRenderer.invoke('team:list'),
  teamDispatch: (text: string) => ipcRenderer.invoke('team:dispatch', text),
  teamApprove: (id: string) => ipcRenderer.invoke('team:approve', id),
  teamReject: (id: string) => ipcRenderer.invoke('team:reject', id),
  teamCustomAdd: (def: unknown) => ipcRenderer.invoke('team:custom-add', def),
  teamCustomRemove: (id: string) => ipcRenderer.invoke('team:custom-remove', id),
  onTeamUpdate: (cb: (t: unknown) => void) => ipcRenderer.on('team:update', (_e, t: unknown) => cb(t)),
  // MCP + skills
  mcpListServers: () => ipcRenderer.invoke('mcp:list-servers'),
  mcpSaveServers: (s: unknown) => ipcRenderer.invoke('mcp:save-servers', s),
  mcpListTools: (config: unknown) => ipcRenderer.invoke('mcp:list-tools', config),
  mcpCallTool: (config: unknown, name: string, args: Record<string, unknown>) => ipcRenderer.invoke('mcp:call-tool', config, name, args),
  skillsList: () => ipcRenderer.invoke('skills:list'),
  skillsLoad: (name: string) => ipcRenderer.invoke('skills:load', name),
  skillsInstall: (gitUrl: string) => ipcRenderer.invoke('skills:install', gitUrl),
  skillsRemove: (name: string) => ipcRenderer.invoke('skills:remove', name),
  // Scheduler
  schedulerList: () => ipcRenderer.invoke('scheduler:list'),
  schedulerAdd: (input: unknown) => ipcRenderer.invoke('scheduler:add', input),
  schedulerRemove: (id: string) => ipcRenderer.invoke('scheduler:remove', id),
  schedulerSetEnabled: (id: string, enabled: boolean) => ipcRenderer.invoke('scheduler:set-enabled', id, enabled),
  schedulerDue: () => ipcRenderer.invoke('scheduler:due'),
  onSchedulerDue: (cb: (t: unknown) => void) => ipcRenderer.on('scheduler:due', (_e, t: unknown) => cb(t)),
  onSchedulerMissed: (cb: (t: unknown) => void) => ipcRenderer.on('scheduler:missed', (_e, t: unknown) => cb(t)),
  // Computer operation
  computerTree: () => ipcRenderer.invoke('computer:tree'),
  computerClick: (name: string) => ipcRenderer.invoke('computer:click', name),
  computerType: (name: string, text: string) => ipcRenderer.invoke('computer:type', name, text),
  computerScreenshot: () => ipcRenderer.invoke('computer:screenshot'),
  // Auto-update
  checkUpdate: () => ipcRenderer.invoke('updater:check'),
  downloadUpdate: () => ipcRenderer.invoke('updater:download'),
  installUpdate: () => ipcRenderer.invoke('updater:install'),
  getUpdaterStatus: () => ipcRenderer.invoke('updater:status'),
  onUpdaterStatus: (cb: (s: unknown) => void) => ipcRenderer.on('updater:status', (_e, s: unknown) => cb(s)),
});
